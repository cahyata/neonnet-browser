#!/usr/bin/env python3
"""Builds ui/blocklist.txt, the domain list behind "Block trackers and ads".

Sources (all open, downloaded when this script runs):
  - EasyList and EasyPrivacy, https://easylist.to  (GPLv3+ / CC BY-SA 3.0)
  - Peter Lowe's ad server list, https://pgl.yoyo.org/adservers/
  - tools/blocklist-extra.txt: a short list kept by hand in this repository

Only the simplest kind of filter is used: "||domain^" (the domain and its subdomains), with no
path, and with no options or only options that narrow it to third-party requests or resource
types. Rules for one site only (domain=...), exceptions (@@), popups and page rules are skipped:
NeonNet never blocks a site's own requests or the page itself, see BlockHandler in main.cpp.

Usage:  python tools/make_blocklist.py [folder with easylist.txt, easyprivacy.txt, pgl.txt]
Without a folder the lists are downloaded.
"""
import os, re, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = {
    'easylist.txt': 'https://easylist.to/easylist/easylist.txt',
    'easyprivacy.txt': 'https://easylist.to/easylist/easyprivacy.txt',
    'pgl.txt': 'https://pgl.yoyo.org/adservers/serverlist.php?hostformat=nohtml&showintro=0&mimetype=plaintext',
}
RULE = re.compile(r'^\|\|([a-z0-9][a-z0-9.-]*\.[a-z0-9-]+)\^(?:\$(.*))?$')
OK_OPTS = {'third-party', '3p', 'script', 'image', 'stylesheet', 'xmlhttprequest', 'xhr', 'object', 'media',
           'font', 'ping', 'subdocument', 'other', 'websocket'}
HOST = re.compile(r'^[a-z0-9][a-z0-9.-]*\.[a-z0-9-]+$')
# endings kept: every two-letter country ending, and the common generic ones (the rest is mostly throw-away names)
GENERIC = {'com', 'net', 'org', 'info', 'biz', 'io', 'tv', 'xyz', 'online', 'site', 'top', 'club', 'app', 'dev', 'cloud',
           'pro', 'mobi', 'name', 'asia', 'link', 'live', 'tech', 'store', 'shop', 'media', 'network', 'digital', 'agency'}


def tld_ok(dom):
    t = dom.rsplit('.', 1)[-1]
    return len(t) == 2 or t in GENERIC


def load(name, folder):
    if folder:
        with open(os.path.join(folder, name), encoding='utf-8', errors='replace') as f:
            return f.read().splitlines()
    with urllib.request.urlopen(SOURCES[name], timeout=120) as r:
        return r.read().decode('utf-8', 'replace').splitlines()


def adblock_domains(lines):
    out = set()
    for ln in lines:
        m = RULE.match(ln.strip().lower())
        if not m:
            continue
        opts = m.group(2)
        if opts and not all(o in OK_OPTS for o in opts.split(',')):
            continue
        out.add(m.group(1))
    return out


def plain_domains(lines):
    out = set()
    for ln in lines:
        ln = ln.split('#')[0].strip().lower()
        if HOST.match(ln):
            out.add(ln)
    return out


def main():
    folder = sys.argv[1] if len(sys.argv) > 1 else None
    domains = set()
    counts = {}
    for name in ('easylist.txt', 'easyprivacy.txt'):
        d = adblock_domains(load(name, folder)); counts[name] = len(d); domains |= d
    d = plain_domains(load('pgl.txt', folder)); counts['pgl.txt'] = len(d); domains |= d
    with open(os.path.join(ROOT, 'tools', 'blocklist-extra.txt'), encoding='utf-8') as f:
        d = plain_domains(f.read().splitlines()); counts['extra'] = len(d); domains |= d
    # a listed parent domain already covers its subdomains
    domains = {d for d in domains if tld_ok(d)}
    keep = set()
    for dom in domains:
        parts = dom.split('.')
        if not any('.'.join(parts[i:]) in domains for i in range(1, len(parts) - 1)):
            keep.add(dom)
    out = os.path.join(ROOT, 'ui', 'blocklist.txt')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# NeonNet tracker and ad list. One domain per line; a domain also blocks its subdomains.\n')
        f.write('# Generated by tools/make_blocklist.py from EasyList and EasyPrivacy (https://easylist.to, GPLv3+ or CC BY-SA 3.0),\n')
        f.write("# Peter Lowe's ad server list (https://pgl.yoyo.org/adservers/) and tools/blocklist-extra.txt. Do not edit by hand.\n")
        for dom in sorted(keep):
            f.write(dom + '\n')
    print('sources:', counts, '-> written', len(keep), 'domains to', out)


if __name__ == '__main__':
    main()
